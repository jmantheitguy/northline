#!/usr/bin/env node

/**
 * Prepare or execute a one-way Northline SQLite -> PostgreSQL migration.
 *
 * This is deliberately separate from the application runtime. SQLite is kept
 * for legacy imports and fixtures; PostgreSQL is the runtime database. The
 * command is read-only by default; writes require --execute and an explicit
 * environment guard.
 */

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";
import Database from "better-sqlite3";
import pg from "pg";

const { Client } = pg;

const sqlIdentifier = (value) => `"${String(value).replaceAll('"', '""')}"`;

function getOption(name) {
  const prefix = `${name}=`;
  const value = process.argv.find((argument) => argument.startsWith(prefix));
  if (value) return value.slice(prefix.length);
  const index = process.argv.indexOf(name);
  if (index === -1) return undefined;
  const next = process.argv[index + 1];
  return next && !next.startsWith("--") ? next : undefined;
}

/** Convert the final SQLite DDL into conservative PostgreSQL DDL. */
export function normalizeTableSql(sql) {
  return sql
    .trim()
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi,
      "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    .replace(/\bINTEGER\s+PRIMARY\s+KEY\b/gi,
      "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    .replace(/\s+COLLATE\s+NOCASE\b/gi, "")
    .replace(/\s+WITHOUT\s+ROWID\b/gi, "")
    .replace(/;\s*$/, "")
    .concat(";");
}

export function normalizeIndexSql(sql) {
  return sql
    .trim()
    .replace(/\s+COLLATE\s+NOCASE\b/gi, "")
    // Additive schema steps may already create a compatibility index that
    // exists in the SQLite snapshot. Keep the import idempotent instead of
    // failing the whole transaction on that expected overlap.
    .replace(/^CREATE\s+(UNIQUE\s+)?INDEX\s+(?!IF\s+NOT\s+EXISTS\s+)/i, (_, unique = "") => `CREATE ${unique}INDEX IF NOT EXISTS `)
    .replace(/;\s*$/, "")
    .concat(";");
}

function tableDependencies(sql) {
  const dependencies = new Set();
  const referencePattern = /\bREFERENCES\s+["`]?([A-Za-z_][A-Za-z0-9_]*)/gi;
  for (const match of sql.matchAll(referencePattern)) dependencies.add(match[1]);
  return dependencies;
}

/** Return parent tables before children so foreign keys can be created safely. */
export function orderTables(tables) {
  const names = new Set(tables.map((table) => table.name));
  const pending = new Map(
    tables.map((table) => [
      table.name,
      new Set([...table.dependencies].filter((name) => name !== table.name && names.has(name))),
    ]),
  );
  const ordered = [];

  while (pending.size) {
    const ready = [...pending.entries()]
      .filter(([, dependencies]) => [...dependencies].every((name) => !pending.has(name)))
      .map(([name]) => name)
      .sort();
    if (!ready.length) {
      throw new Error(`Unable to order PostgreSQL tables; dependency cycle near: ${[...pending.keys()].join(", ")}`);
    }
    for (const name of ready) {
      ordered.push(tables.find((table) => table.name === name));
      pending.delete(name);
    }
  }
  return ordered;
}

export function inspectSqlite(source) {
  const tableRows = source
    .prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND sql IS NOT NULL")
    .all();
  const tables = tableRows.map((row) => ({
    name: row.name,
    sql: normalizeTableSql(row.sql),
    dependencies: tableDependencies(row.sql),
    columns: source.prepare(`PRAGMA table_info(${sqlIdentifier(row.name)})`).all(),
    rowCount: source.prepare(`SELECT COUNT(*) AS count FROM ${sqlIdentifier(row.name)}`).get().count,
  }));
  const indexes = source
    .prepare("SELECT name, sql FROM sqlite_master WHERE type='index' AND name NOT LIKE 'sqlite_autoindex_%' AND sql IS NOT NULL")
    .all()
    .map((row) => ({ name: row.name, sql: normalizeIndexSql(row.sql) }));
  return { tables: orderTables(tables), indexes };
}

function printPlan(sourcePath, plan) {
  const totalRows = plan.tables.reduce((total, table) => total + Number(table.rowCount), 0);
  console.log(`SQLite source: ${sourcePath}`);
  console.log(`Tables: ${plan.tables.length}; rows to copy: ${totalRows}; indexes: ${plan.indexes.length}`);
  for (const table of plan.tables) console.log(`  ${table.name}: ${table.rowCount} rows`);
  console.log("Dry run only. No PostgreSQL connection was opened.");
}

function redactTarget(message, targetUrl) {
  return String(message).replaceAll(targetUrl || "", "[redacted target]");
}

async function copyRows(client, source, table) {
  const columns = table.columns.map((column) => column.name);
  if (!columns.length) return;
  const existing = await client.query(`SELECT COUNT(*)::bigint AS count FROM ${sqlIdentifier(table.name)}`);
  if (Number(existing.rows[0].count) !== 0) {
    throw new Error(`Target table ${table.name} is not empty; migration refuses to merge or overwrite data`);
  }
  const rows = source.prepare(`SELECT * FROM ${sqlIdentifier(table.name)}`).all();
  if (!rows.length) return;
  const columnSql = columns.map(sqlIdentifier).join(", ");
  const placeholders = columns.map((_, index) => `$${index + 1}`).join(", ");
  const insert = `INSERT INTO ${sqlIdentifier(table.name)} (${columnSql}) VALUES (${placeholders})`;
  for (const row of rows) await client.query(insert, columns.map((column) => row[column]));
}

async function resetIdentity(client, table) {
  const idColumn = table.columns.find((column) => column.name === "id");
  if (!idColumn || !Number(idColumn.pk)) return;
  const sequence = await client.query("SELECT pg_get_serial_sequence($1, $2) AS name", [table.name, "id"]);
  const sequenceName = sequence.rows[0]?.name;
  if (!sequenceName) return;
  const maximum = await client.query(`SELECT MAX(${sqlIdentifier("id")}) AS maximum FROM ${sqlIdentifier(table.name)}`);
  if (maximum.rows[0]?.maximum !== null && maximum.rows[0]?.maximum !== undefined) {
    await client.query("SELECT setval($1::regclass, $2::bigint, true)", [sequenceName, maximum.rows[0].maximum]);
  }
}

async function createCompatibilityIndexes(client) {
  // SQLite's users.email column uses COLLATE NOCASE. The normalized
  // PostgreSQL table definition cannot carry that SQLite collation, so keep
  // the same uniqueness rule with an expression index.
  await client.query('CREATE UNIQUE INDEX IF NOT EXISTS users_email_nocase_idx ON "users" (LOWER("email"))');
}

async function applyLatestAdditiveSchema(client) {
  // These changes were added after some production SQLite snapshots were
  // taken. Keep the import forward-only so older snapshots remain usable by
  // the current PostgreSQL runtime.
  await client.query('ALTER TABLE "time_entries" ADD COLUMN IF NOT EXISTS "paused_at" TEXT');
  await client.query('ALTER TABLE "time_entries" ADD COLUMN IF NOT EXISTS "paused_seconds" INTEGER NOT NULL DEFAULT 0');
  await client.query(`
    CREATE TABLE IF NOT EXISTS "task_assignees" (
      "task_id" INTEGER NOT NULL REFERENCES "tasks"("id") ON DELETE CASCADE,
      "user_id" INTEGER NOT NULL REFERENCES "users"("id") ON DELETE CASCADE,
      "assigned_by" INTEGER REFERENCES "users"("id") ON DELETE SET NULL,
      "created_at" TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY ("task_id", "user_id")
    )
  `);
  await client.query(`
    INSERT INTO "task_assignees" ("task_id", "user_id")
    SELECT "id", "assignee_id" FROM "tasks"
    WHERE "assignee_id" IS NOT NULL
    ON CONFLICT ("task_id", "user_id") DO NOTHING
  `);
  await client.query('CREATE INDEX IF NOT EXISTS task_assignees_user_idx ON "task_assignees" ("user_id", "task_id")');
  await client.query("INSERT INTO schema_migrations(version,name) VALUES(24,'multi-assignee tasks and pauseable time entries') ON CONFLICT(version) DO NOTHING");
}

async function applySchemaHardening(client) {
  const orphanedEvents = await client.query(`
    SELECT COUNT(*)::text AS count
    FROM "calendar_events" event
    LEFT JOIN "collab_requests" request ON request."id"=event."collab_request_id"
    WHERE event."collab_request_id" IS NOT NULL AND request."id" IS NULL
  `);
  if (Number(orphanedEvents.rows[0]?.count || 0) > 0) {
    throw new Error("Cannot apply schema hardening: calendar_events contains orphaned collaboration references");
  }
  await client.query(`
    DO $$
    BEGIN
      IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname='calendar_events_collab_request_id_fkey'
          AND conrelid='public.calendar_events'::regclass
      ) THEN
        ALTER TABLE "calendar_events"
          ADD CONSTRAINT "calendar_events_collab_request_id_fkey"
          FOREIGN KEY ("collab_request_id") REFERENCES "collab_requests"("id") ON DELETE SET NULL;
      END IF;
    END
    $$;
  `);
  const checks = [
    ["calendars", "calendars_calendar_type_check", `"calendar_type" IN ('personal','streaming')`],
    ["calendars", "calendars_visibility_check", `"visibility" IN ('private','team','public')`],
    ["calendar_events", "calendar_events_event_kind_check", `"event_kind" IN ('event','stream','collab')`],
    ["calendar_events", "calendar_events_visibility_check", `"visibility" IN ('calendar','private','team','public','busy')`],
    ["calendar_events", "calendar_events_collab_enabled_check", `"collab_enabled" IN (0,1)`],
    ["collab_requests", "collab_requests_status_check", `"status" IN ('pending','countered','accepted','declined','cancelled')`],
    ["collab_request_participants", "collab_request_participants_status_check", `"status" IN ('pending','countered','accepted','declined','cancelled')`],
    ["collab_reschedule_proposals", "collab_reschedule_proposals_status_check", `"status" IN ('pending','accepted','declined','cancelled')`],
    ["collab_reschedule_responses", "collab_reschedule_responses_status_check", `"status" IN ('pending','accepted','declined')`],
    ["collab_notifications", "collab_notifications_status_check", `"status" IN ('pending','sent','failed')`],
  ];
  for (const [table, name, expression] of checks) {
    await client.query(`
      DO $$
      BEGIN
        IF NOT EXISTS (
          SELECT 1 FROM pg_constraint
          WHERE conname='${name}' AND conrelid='public.${table}'::regclass
        ) THEN
          ALTER TABLE "${table}" ADD CONSTRAINT "${name}" CHECK (${expression});
        END IF;
      END
      $$;
    `);
  }
  await client.query('CREATE INDEX IF NOT EXISTS calendar_events_collab_request_idx ON "calendar_events" ("collab_request_id")');
  await client.query("INSERT INTO schema_migrations(version,name) VALUES(26,'schema hardening and collaboration integrity') ON CONFLICT(version) DO NOTHING");
}

export async function executeMigration({ source, targetUrl, plan }) {
  const client = new Client({ connectionString: targetUrl });
  await client.connect();
  try {
    await client.query("BEGIN");
    for (const table of plan.tables) await client.query(table.sql);
    for (const table of plan.tables) await copyRows(client, source, table);
    await applyLatestAdditiveSchema(client);
    await applySchemaHardening(client);
    for (const index of plan.indexes) await client.query(index.sql);
    await createCompatibilityIndexes(client);
    for (const table of plan.tables) await resetIdentity(client, table);
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK").catch(() => undefined);
    throw error;
  } finally {
    await client.end();
  }
}

async function main() {
  const sourcePath = getOption("--source") || process.env.NORTHLINE_SQLITE_PATH ||
    path.join(process.env.NORTHLINE_DATA_DIR || path.join(process.cwd(), "data"), "northline.db");
  const execute = process.argv.includes("--execute");
  const targetUrl = process.env.DATABASE_URL;
  if (!fs.existsSync(sourcePath)) throw new Error(`SQLite source does not exist: ${sourcePath}`);
  const source = new Database(sourcePath, { readonly: true, fileMustExist: true });
  try {
    const plan = inspectSqlite(source);
    if (!execute) return printPlan(sourcePath, plan);
    if (!targetUrl) throw new Error("DATABASE_URL is required for --execute");
    const target = process.env.NORTHLINE_MIGRATION_TARGET;
    const productionConfirmed = process.env.NORTHLINE_MIGRATION_CONFIRM === "I_UNDERSTAND_NORTHLINE_PRODUCTION_CUTOVER";
    if (target !== "staging" && !(target === "production" && productionConfirmed)) {
      throw new Error("Refusing to write: set NORTHLINE_MIGRATION_TARGET=staging, or use the production target with NORTHLINE_MIGRATION_CONFIRM=I_UNDERSTAND_NORTHLINE_PRODUCTION_CUTOVER");
    }
    await executeMigration({ source, targetUrl, plan });
    console.log(`Migration completed for ${plan.tables.length} tables.`);
  } catch (error) {
    throw new Error(redactTarget(error instanceof Error ? error.message : String(error), targetUrl));
  } finally {
    source.close();
  }
}

